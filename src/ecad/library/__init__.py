"""Generated-component registry.

``get(name_or_lib_id)`` serves Component classes generated by
``src.ecad.ingest.codegen``. It discovers vendor subpackages under this
directory (``library/espressif/…``) plus any registered extra search paths,
loads the matching ``<id>.py`` module, and applies its ``<id>_overrides.py``
companion when present:

- if the overrides module defines ``refine(cls)``, the returned class (or
  the original, if ``refine`` mutates in place / returns ``None``) is served;
- otherwise, a subclass of the generated class defined in the overrides
  module is served directly. The generated class is injected into the
  overrides module namespace under its own name before execution, so an
  override can simply write ``class ESP32_S3_WROOM_1(ESP32_S3_WROOM_1): …``
  without importing anything.

Generated modules are found by their deterministic module id
(``ESP32-S3-WROOM-1`` → ``esp32_s3_wroom_1``), by ``part_name`` or by
``lib_id``. Lookup is deterministic (sorted directories and files).
"""

from __future__ import annotations

import hashlib
import importlib.util
import re
import sys
from pathlib import Path
from types import ModuleType

from ..component import Component

_LIB_ROOT = Path(__file__).resolve().parent
_EXTRA_PATHS: list[Path] = []
_CLASS_CACHE: dict[str, type[Component]] = {}   # keyed by str(module path)


def add_search_path(path: Path) -> None:
    """Register an extra directory of generated modules (tests, staging)."""
    p = Path(path).resolve()
    if p not in _EXTRA_PATHS:
        _EXTRA_PATHS.append(p)


def remove_search_path(path: Path) -> None:
    """Unregister a directory added with ``add_search_path``."""
    p = Path(path).resolve()
    if p in _EXTRA_PATHS:
        _EXTRA_PATHS.remove(p)


def clear_cache() -> None:
    """Drop cached classes (needed after regenerating or editing overrides)."""
    _CLASS_CACHE.clear()


def _norm(s: str) -> str:
    return re.sub(r"[^0-9A-Za-z]+", "_", s).strip("_").lower()


def _search_dirs() -> list[Path]:
    vendors = sorted(
        d for d in _LIB_ROOT.iterdir()
        if d.is_dir() and not d.name.startswith((".", "_"))
    )
    return vendors + list(_EXTRA_PATHS)


def _module_files(directory: Path) -> list[Path]:
    return sorted(
        p for p in directory.glob("*.py")
        if not p.stem.startswith("_") and not p.stem.endswith("_overrides")
    )


def _load_module(path: Path, inject: dict | None = None) -> ModuleType:
    tag = hashlib.sha1(str(path).encode()).hexdigest()[:8]
    mod_name = f"_ecad_library_{path.stem}_{tag}"
    spec = importlib.util.spec_from_file_location(mod_name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load generated module {path}")
    module = importlib.util.module_from_spec(spec)
    for key, value in (inject or {}).items():
        setattr(module, key, value)
    sys.modules[mod_name] = module
    spec.loader.exec_module(module)
    return module


def _component_class(module: ModuleType, path: Path) -> type[Component]:
    """The Component subclass defined in a generated module (first wins)."""
    for obj in vars(module).values():
        if (isinstance(obj, type) and issubclass(obj, Component)
                and obj is not Component
                and obj.__module__ == module.__name__):
            return obj
    raise LookupError(f"{path} defines no Component subclass")


def _apply_overrides(cls: type[Component], path: Path) -> type[Component]:
    """Apply ``<id>_overrides.py`` next to a generated module, if present."""
    override_path = path.with_name(f"{path.stem}_overrides.py")
    if not override_path.is_file():
        return cls
    module = _load_module(override_path, inject={cls.__name__: cls})
    refine = getattr(module, "refine", None)
    if callable(refine):
        refined = refine(cls)
        if isinstance(refined, type) and issubclass(refined, Component):
            return refined
        return cls
    for obj in vars(module).values():
        if (isinstance(obj, type) and issubclass(obj, Component)
                and obj is not cls and obj.__module__ == module.__name__
                and (issubclass(obj, cls) or obj.part_name == cls.part_name)):
            return obj
    return cls


def _get_class(path: Path) -> type[Component]:
    key = str(path)
    cached = _CLASS_CACHE.get(key)
    if cached is not None:
        return cached
    cls = _apply_overrides(_component_class(_load_module(path), path), path)
    _CLASS_CACHE[key] = cls
    return cls


def get(name_or_lib_id: str) -> type[Component]:
    """Resolve a part name, module id, or ``Lib:Name`` lib_id to its class.

    Raises KeyError when no generated module matches.
    """
    if not name_or_lib_id:
        raise KeyError("empty component name")
    key = _norm(name_or_lib_id.split(":")[-1])

    # Pass 1: deterministic module-id match — no imports of non-matches.
    for directory in _search_dirs():
        for path in _module_files(directory):
            if _norm(path.stem) == key:
                return _get_class(path)

    # Pass 2: match by declared part_name / lib_id (loads modules).
    for directory in _search_dirs():
        for path in _module_files(directory):
            cls = _get_class(path)
            if (name_or_lib_id in (cls.part_name, cls.lib_id)
                    or _norm(cls.part_name) == key):
                return cls

    searched = ", ".join(str(d) for d in _search_dirs()) or "<none>"
    raise KeyError(
        f"no generated component matches {name_or_lib_id!r} "
        f"(searched: {searched})")


def names() -> list[str]:
    """All discoverable generated part module ids (sorted, deduplicated)."""
    out = {p.stem for d in _search_dirs() for p in _module_files(d)}
    return sorted(out)
