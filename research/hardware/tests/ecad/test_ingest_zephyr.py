def test_ensure_missing_clone_gives_clone_command(tmp_path):
    root = _fake_repo(tmp_path)
    import shutil
    shutil.rmtree(root / "data" / "zephyr" / "hal_espressif")
    with pytest.raises(ZephyrTreeError) as exc:
        ensure(root)
    msg = str(exc.value)
    assert "git clone" in msg and "hal_espressif" in msg
    assert HSHA in msg  # ref-pinned repo: fetch+checkout by sha
    assert "sparse-checkout set components/soc" in msg


def test_ensure_drifted_sha_raises_with_fix(tmp_path):
    root = _fake_repo(tmp_path)
    _write(root / "data" / "zephyr" / "zephyr" / ".git" / "HEAD", "f" * 40)
    with pytest.raises(ZephyrTreeError) as exc:
        ensure(root)
    msg = str(exc.value)
    assert ZSHA in msg and "f" * 40 in msg
    assert "rm -rf" in msg and "--branch v3.7.2" in msg


def test_git_head_symbolic_ref_resolution(tmp_path):
    root = _fake_repo(tmp_path)
    gd = root / "data" / "zephyr" / "zephyr" / ".git"
    _write(gd / "HEAD", "ref: refs/heads/main\n")
    _write(gd / "refs" / "heads" / "main", ZSHA + "\n")
    ensure(root)  # resolves through the loose ref, still matches PIN


def test_soc_source_policy_and_needs_fallback(tmp_path):
    tree = ensure(_fake_repo(tmp_path))
    assert tree.soc_source("esp32s3") == "lts"
    assert tree.soc_source("esp32h2") == "fallback"
    with pytest.raises(NeedsFallbackTree) as exc:
        tree.soc("esp32h2")
    msg = str(exc.value)
    assert "git clone" in msg and "--branch v4.4.1" in msg
    assert "zephyr-fallback" in msg
    # once the fallback tree exists, esp32h2 parses from it
    fb = tree.fallback_dir
    _write(fb / "include" / "zephyr" / "dt-bindings" / "pinctrl"
           / "esp32h2-pinctrl.h", PINCTRL)
    _write(fb / "include" / "zephyr" / "dt-bindings" / "pinctrl"
           / "esp32h2-gpio-sigmap.h", SIGMAP)
    _write(fb / "dts" / "riscv" / "espressif" / "esp32h2"
           / "esp32h2_common.dtsi", DTSI)
    soc = tree.soc("esp32h2")
    assert soc.strapping == STRAPPING["esp32h2"] == (8, 9, 25)


