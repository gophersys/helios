def test_parse_pinctrl_joins_continuations_and_groups():
    entries = parse_pinctrl(PINCTRL)
    by_key = {(e.group, e.gpio): e for e in entries}
    assert len(entries) == 6
    i2c = by_key[("I2C0_SDA", 2)]
    assert i2c.sig_in == "ESP_I2CEXT0_SDA_IN"
    assert i2c.sig_out == "ESP_I2CEXT0_SDA_OUT"


def test_parse_pinctrl_nosig_sentinel():
    entries = parse_pinctrl(PINCTRL)
    ledc = next(e for e in entries if e.group == "LEDC_CH0")
    assert ledc.sig_in is None  # ESP_NOSIG -> output-only signal
    assert ledc.sig_out == "ESP_LEDC_LS_SIG_OUT0"
    miso = next(e for e in entries if e.group == "SPIM2_MISO")
    assert miso.sig_out is None
    assert miso.sig_in == "ESP_FSPIQ_IN"


def test_parse_sigmap_numeric_defines_only():
    ids = parse_sigmap(SIGMAP)
    assert ids["ESP_U0TXD_OUT"] == 12
    assert ids["ESP_FSPIQ_IN"] == 61
    assert "ESP_NOSIG" not in ids  # alias of ESP_SIG_INVAL, not numeric


def test_parse_dtsi_dual_banks_and_labels():
    assert parse_dtsi_ngpios(DTSI) == (32, 22)
    labels = parse_dtsi_labels(DTSI)
    for expected in ("uart0", "gpio", "gpio0", "gpio1", "twai",
                     "pinctrl", "flash", "flash0"):
        assert expected in labels
    # twai's node name is can@... — label wins, node name is irrelevant
    assert "can" not in labels
    assert labels == tuple(sorted(set(labels)))


def test_parse_io_mux_pad_indirection_and_dedupe():
    funcs = parse_io_mux(IO_MUX)
    assert set(funcs) == {0, 13, 43, 44, 46}
    # pad U0TXD maps to GPIO43; functions ordered by IO MUX index
    assert funcs[43] == ("U0TXD", "GPIO43", "CLK_OUT1")
    # duplicate _0 alias deduped, real functions with digits kept
    assert funcs[0] == ("GPIO0",)
    assert funcs[13] == ("GPIO13", "FSPIIO7", "SUBSPIQ", "FSPIQ")
    assert funcs[46] == ("GPIO46",)


def test_parse_input_only_mask_shapes():
    assert parse_input_only(SOC_CAPS_S3) == ()          # S3: none
    assert parse_input_only(SOC_CAPS_ESP32) == (34, 35, 36, 37, 38, 39)
    assert parse_input_only(SOC_CAPS_C3) == ()
    assert parse_input_only("") == ()


def test_parse_pin_file_real_format():
    pin = parse_pin_file(PIN_FILE)
    assert pin["zephyr"]["sha"] == "bbbf8b30094dacd0d6830946ba206bcec8af6b0c"
    assert pin["zephyr"]["tag"] == "v3.7.2"  # inline comment stripped
    assert pin["zephyr"]["sparse"] == [
        "dts/xtensa/espressif", "dts/riscv/espressif",
        "include/zephyr/dt-bindings/pinctrl", "boards/espressif"]
    assert pin["hal_espressif"]["sparse"] == ["components/soc"]
    assert pin["fallback"]["zephyr_tag"] == "v4.4.1"


