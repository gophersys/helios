@pytest.fixture(scope="module")
def tree() -> ZephyrTree:
    assert REPO_ROOT is not None
    return ensure(REPO_ROOT)


@live
def test_live_ensure_matches_pin(tree):
    assert tree.pin["zephyr"]["tag"] == "v3.7.2"
    assert tree.soc_source("esp32s3") == "lts"
    assert tree.soc_source("esp32h2") == "fallback"


@live
def test_live_esp32s3(tree):
    soc = tree.soc("esp32s3")
    assert soc.gpio_count == 54          # dtsi banks 32 + 22
    assert soc.signals["UART0_TX"] == 43
    assert soc.signals["UART0_RX"] == 44
    assert soc.signals["SPIM2_MISO"] == 13  # FSPIQ home pad
    assert soc.gpios[43].iomux_functions[0] == "U0TXD"
    assert soc.strapping == (0, 3, 45, 46)
    assert 22 not in soc.gpios           # GPIO22-25 pads do not exist on S3
    for label in ("uart0", "uart1", "i2c0", "spi2", "twai", "ledc0",
                  "gpio0", "gpio1", "usb_serial"):
        assert label in soc.peripherals


@live
def test_live_input_only_truth(tree):
    # S3: no input-only pins (soc_caps: "No GPIO is input only"; the
    # datasheet pin table lists GPIO46 as I/O/T).
    s3 = tree.soc("esp32s3")
    assert s3.gpios[46].input_only is False
    assert not any(g.input_only for g in s3.gpios.values())
    # The input-only GPIO46 is an ESP32-S2 fact:
    s2 = tree.soc("esp32s2")
    assert s2.gpios[46].input_only is True
    # ESP32: GPIO34-39 are input-only.
    esp32 = tree.soc("esp32")
    assert all(esp32.gpios[n].input_only for n in (34, 35, 36, 37, 38, 39))
    assert esp32.gpios[33].input_only is False


@live
def test_live_esp32(tree):
    soc = tree.soc("esp32")
    assert soc.gpio_count == 40          # banks 32 + 8
    assert soc.signals["UART0_TX"] == 1  # U0TXD home pad
    assert soc.signals["UART0_RX"] == 3
    assert soc.strapping == (0, 2, 5, 12, 15)


@live
def test_live_all_lts_socs_parse(tree):
    counts = {"esp32": 40, "esp32s2": 54, "esp32s3": 54,
              "esp32c3": 26, "esp32c6": 30}
    for name, expected in counts.items():
        soc = tree.soc(name)
        assert soc.gpio_count == expected, name
        assert soc.gpios and soc.signals, name
        assert "uart0" in soc.peripherals, name
        assert soc.strapping == STRAPPING[name], name
        # every default placement points at a GPIO with a real IO MUX pad
        assert all(g in soc.gpios for g in soc.signals.values()), name


@live
def test_live_esp32h2_fallback_policy(tree):
    assert tree.soc_source("esp32h2") == "fallback"
    if tree.fallback_dir.is_dir():
        soc = tree.soc("esp32h2")
        assert soc.strapping == (8, 9, 25)
        assert soc.gpios
    else:
        with pytest.raises(NeedsFallbackTree) as exc:
            tree.soc("esp32h2")
        assert "v4.4.1" in str(exc.value)
