"""Zephyr/HAL ingestion parsers.

Two layers:
- fixture-string unit tests for every parser (run everywhere; fixtures
  mirror the REAL formats quoted in data/zephyr/VALIDATION.md), plus a
  fake-tree assembly/ensure() suite in tmp_path;
- live tests against the pinned clones in data/zephyr (skip-guarded).

Note on input-only pins: the ESP32-S3 has NO input-only GPIOs — its
soc_caps.h states "No GPIO is input only" and the datasheet pin table
lists GPIO46 as I/O/T.  The famous input-only GPIO46 belongs to the
ESP32-S2 (asserted below); on the original ESP32 it is GPIO34-39.
"""

