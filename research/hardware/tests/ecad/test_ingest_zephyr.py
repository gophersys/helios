ZSHA = "bbbf8b30094dacd0d6830946ba206bcec8af6b0c"
HSHA = "01fc4ec49b8b178d7aea765cdb8709311ee4c50b"


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def _fake_repo(tmp_path: Path) -> Path:
    root = tmp_path / "repo"
    dz = root / "data" / "zephyr"
    _write(dz / "PIN", PIN_FILE)
    _write(dz / "zephyr" / ".git" / "HEAD", ZSHA + "\n")
    _write(dz / "hal_espressif" / ".git" / "HEAD", HSHA + "\n")
    pinctrl = dz / "zephyr" / "include" / "zephyr" / "dt-bindings" / "pinctrl"
    _write(pinctrl / "esp32s3-pinctrl.h", PINCTRL)
    _write(pinctrl / "esp32s3-gpio-sigmap.h", SIGMAP)
    _write(dz / "zephyr" / "dts" / "xtensa" / "espressif" / "esp32s3"
           / "esp32s3_common.dtsi", DTSI)
    _write(dz / "zephyr" / "dts" / "riscv" / "espressif" / ".keep", "")
    _write(dz / "zephyr" / "boards" / "espressif" / ".keep", "")
    hal_soc = dz / "hal_espressif" / "components" / "soc"
    _write(hal_soc / "esp32s3" / "include" / "soc" / "io_mux_reg.h", IO_MUX)
    _write(hal_soc / "esp32s3" / "include" / "soc" / "soc_caps.h", SOC_CAPS_S3)
    # esp32h2 exists HAL-side only (mirrors the real LTS tree)
    _write(hal_soc / "esp32h2" / "include" / "soc" / "io_mux_reg.h", IO_MUX)
    return root


def test_ensure_ok_and_soc_assembly(tmp_path):
    tree = ensure(_fake_repo(tmp_path))
    soc = tree.soc("esp32s3")
    assert soc.gpio_count == 54  # 32 + 22
    # native-pin selection: UART0_TX offered on 42 and 43, but only
    # GPIO43's IO MUX carries U0TXD -> 43 wins
    assert soc.signals == {"SPIM2_MISO": 13, "UART0_RX": 44, "UART0_TX": 43}
    assert soc.gpios[43].iomux_functions == ("U0TXD", "GPIO43", "CLK_OUT1")
    assert soc.gpios[46].input_only is False
    assert soc.strapping == (0, 3, 45, 46)
    assert "twai" in soc.peripherals and "uart0" in soc.peripherals
    assert tree.soc("esp32s3") is soc  # cached


