// generatedNotice is the provenance line every emitted document opens with. It names the schema
// version, the cell and the overlay that produced the file, so a human who finds the file in a
// repository learns where it came from and is told not to edit it — the one instruction that keeps
// the drift check meaningful. It is derived only from Resolved, so it stays deterministic.
func generatedNotice(resolved *Resolved) string {
	return "<!-- generated by agentprofile (schemaVersion " + strconv.Itoa(resolved.SchemaVersion) +
		", role " + string(resolved.Target.Role) +
		", harness " + string(resolved.Target.Harness) +
		", overlay " + overlayLabel(resolved.Repository) +
		"). Do not edit: edit the profile document and re-render. -->\n\n"
}

// overlayLabel renders the applied overlay for the provenance line, naming the base matrix
// explicitly rather than leaving a reader to interpret an empty field.
func overlayLabel(repository string) string {
	if repository == "" {
		return "none"
	}
	return repository
}
